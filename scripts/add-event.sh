#!/bin/bash
# Добавить событие в Календарь вручную — такие команды предлагает /process-inbox:
#   ~/bin/add-event.sh "Название" "YYYY-MM-DD HH:MM" [минут] [календарь]
# Длительность по умолчанию 60, календарь — brain.
# Реализация общая с командой /e бота (tg-inbox.py): тот же AppleScript,
# аргументы уходят в osascript аргументами, а не подстановкой в код.
# Код выхода: 0 — создано, 1 — ошибка Календаря, 2 — неверные аргументы.
exec /usr/bin/python3 "$(dirname "$0")/tg-inbox.py" add-event "$@"
